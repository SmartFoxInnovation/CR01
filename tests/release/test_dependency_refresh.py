"""Dependency selection and metadata regressions, not cryptographic assurance."""
import hashlib
from importlib import metadata
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from cr01_sc.native import native_environment
from tools.native import openssl_flags
from tools import dependencies
from tools.build_release import collect_release_paths

ROOT=Path(__file__).resolve().parents[2]


class DependencyRefreshTests(unittest.TestCase):
    def test_noncommercial_licence_and_version_neutral_notice(self):
        self.assertEqual(hashlib.sha256((ROOT/'LICENSE').read_bytes()).hexdigest(),
                         'c0ea4a896d2c8c394b29f9427589996db826cd501c512279ff0ed3ef48fabbe5')
        notice=(ROOT/'NOTICE').read_text(encoding='utf-8')
        self.assertNotIn('v0.2.0',notice)
        self.assertIn('Required Notice: CR01-SC is licensed under PolyForm Noncommercial 1.0.0.',notice)
        self.assertIn('Commercial use requires an explicit commercial license.',notice)

    def test_lock_generator_headers_resolve_and_runtime_matches_locks(self):
        inventory=set(collect_release_paths())
        for name in ('requirements.lock','config/native-packages.lock'):
            first=(ROOT/name).read_text().splitlines()[0]
            self.assertEqual(first,'# Generated by tools/locks.py')
            self.assertIn(first.removeprefix('# Generated by '),inventory)
        for line in (ROOT/'requirements.lock').read_text().splitlines():
            if '==' in line and not line.startswith('#'):
                name,version=line.split('==',1)
                self.assertEqual(metadata.version(name),version)

    def test_explicit_prefix_is_used_for_headers_linker_and_runtime_path(self):
        with tempfile.TemporaryDirectory(prefix='cr01 prefix with spaces ') as directory:
            root=Path(directory)
            (root/'include/openssl').mkdir(parents=True)
            (root/'include/openssl/opensslv.h').touch()
            (root/'lib').mkdir()
            (root/'lib/libcrypto.a').touch()
            (root/'lib/libssl.a').touch()
            (root/'bin').mkdir()
            (root/'bin/libcrypto-3-x64.dll').touch()
            with patch.dict(os.environ,{'OPENSSL_ROOT':str(root)}):
                flags=openssl_flags(tls=True)
                self.assertIn(str(root/'include'),flags)
                self.assertIn(str(root/'lib'),flags)
                self.assertEqual(flags[-2:],['-lssl','-lcrypto'])
                env=native_environment()
                if os.name=='nt':
                    self.assertEqual(env['PATH'].split(os.pathsep)[0],str(root/'bin'))

    def test_invalid_prefix_cannot_silently_link_or_load_global_library(self):
        with tempfile.TemporaryDirectory() as directory, patch.dict(os.environ,{'OPENSSL_ROOT':directory}):
            with self.assertRaisesRegex(ValueError,'development headers/libraries'):
                openssl_flags()
            if os.name=='nt':
                with self.assertRaisesRegex(ValueError,'Windows libcrypto runtime'):
                    native_environment()
            root=Path(directory)
            (root/'include/openssl').mkdir(parents=True)
            (root/'include/openssl/opensslv.h').touch()
            (root/'lib').mkdir()
            (root/'lib/libcrypto.a').touch()
            # A valid crypto-only prefix cannot borrow TLS from a global install.
            openssl_flags()
            with self.assertRaisesRegex(ValueError,'development headers/libraries'):
                openssl_flags(tls=True)

    def test_extracted_openssl_inventory_does_not_report_old_global_version(self):
        with tempfile.TemporaryDirectory() as directory:
            base=Path(directory);root=base/'ucrt64'
            (root/'bin').mkdir(parents=True)
            executable=root/'bin'/('openssl.exe' if os.name=='nt' else 'openssl')
            executable.touch()
            licence=root/'share/licenses/openssl/LICENSE'
            licence.parent.mkdir(parents=True);licence.write_text('synthetic fixture')
            (base/'.PKGINFO').write_text('pkgname = mingw-w64-ucrt-x86_64-openssl\npkgver = 3.6.5-1\n')
            with patch.dict(os.environ,{'OPENSSL_ROOT':str(root)}), \
                 patch('tools.dependencies.run_command',return_value='OpenSSL 3.6.5 fixture'), \
                 patch('tools.dependencies.pacman_version',return_value='3.6.1-3'):
                selected=next(item for item in dependencies.collect_native_notices() if item.name.endswith('openssl'))
            self.assertEqual(selected.version,'3.6.5-1')
            self.assertEqual(selected.license_files[0].path,'ucrt64/share/licenses/openssl/LICENSE')
            self.assertNotIn(directory,selected.license_files[0].path)
            with patch.dict(os.environ,{'OPENSSL_ROOT':str(root)}), \
                 patch('tools.dependencies.run_command',return_value='OpenSSL 3.6.1 fixture'), \
                 patch('tools.dependencies.pacman_version',return_value='3.6.1-3'):
                with self.assertRaisesRegex(ValueError,'versions disagree'):
                    dependencies.collect_native_notices()
