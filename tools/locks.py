"""Generate recorded dependency versions for a CR01-SC technical preview."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.dependencies import generate_third_party_license_report


PYTHON_LOCK = ROOT / "requirements.lock"
NATIVE_LOCK_TXT = ROOT / "config" / "native-packages.lock"
NATIVE_LOCK_JSON = ROOT / "config" / "native-packages.lock.json"


def render_python_lock(report: dict[str, Any]) -> str:
    packages = sorted(
        report["python_runtime_packages"],
        key=lambda item: item["name"].lower(),
    )
    lines = [
        "# Generated by tools/locks.py",
        "# Recorded Python runtime versions for this CR01-SC technical preview.",
        "# Development constraints live in requirements.txt and pyproject.toml.",
        "",
    ]
    lines.extend(f"{package['name']}=={package['version']}" for package in packages)
    lines.append("")
    return "\n".join(lines)


def render_native_lock(report: dict[str, Any]) -> str:
    lines = [
        "# Generated by tools/locks.py",
        "# Recorded MSYS2 UCRT64 package versions for this CR01-SC technical preview.",
        "",
    ]
    for package in report["native_packages"]:
        version = package["version"] or "unavailable"
        lines.append(f"{package['name']}={version}")
    lines.append("")
    return "\n".join(lines)


def render_markdown(result: dict[str, Any]) -> str:
    summary = result["summary"]
    lines = [
        "# CR01-SC Release Dependency Locks",
        "",
        "## Summary",
        "",
    ]
    for key, value in summary.items():
        lines.append(f"- {key}: {value}")

    lines.extend(
        [
            "",
            "## Python Runtime Lock",
            "",
            "| Package | Version |",
            "| --- | ---: |",
        ]
    )
    for package in result["python_runtime_packages"]:
        lines.append(f"| {package['name']} | {package['version']} |")

    lines.extend(
        [
            "",
            "## Native Build Lock",
            "",
            "| Package | Version | Tool version |",
            "| --- | ---: | --- |",
        ]
    )
    for package in result["native_packages"]:
        lines.append(f"| {package['name']} | {package['version'] or 'unavailable'} | {package['tool_version'] or 'n/a'} |")

    lines.extend(
        [
            "",
            "## Boundary",
            "",
            "- These locks pin local release-build dependency versions; they do not vendor the dependencies.",
            "- Regenerate before tagging a release and review third-party notices for the exact distributed artifact.",
            "- This is release reproducibility evidence, not legal advice, FIPS validation, or supply-chain attestation.",
        ]
    )
    return "\n".join(lines)


def generate_release_locks(out_dir: Path, *, update_locks: bool = False) -> dict[str, Any]:
    report = generate_third_party_license_report()
    python_packages = sorted(report["python_runtime_packages"], key=lambda item: item["name"].lower())
    native_packages = list(report["native_packages"])
    result = {
        "summary": {
            "status": "ready" if all(package["version"] for package in native_packages) else "incomplete",
            "python_lock": str(PYTHON_LOCK.relative_to(ROOT)),
            "native_lock": str(NATIVE_LOCK_TXT.relative_to(ROOT)),
            "native_lock_json": str(NATIVE_LOCK_JSON.relative_to(ROOT)),
            "python_runtime_package_count": len(python_packages),
            "native_package_count": len(native_packages),
            "generator": "tools/locks.py",
            "canonical_locks_updated": update_locks,
            "claim_boundary": "Exact local dependency-version lock evidence only; not a supply-chain attestation or compliance validation.",
        },
        "python_runtime_packages": python_packages,
        "native_packages": native_packages,
    }

    out_dir.mkdir(parents=True, exist_ok=True)
    candidates = ((PYTHON_LOCK, "requirements.lock", render_python_lock(report)),
                  (NATIVE_LOCK_TXT, "native-packages.lock", render_native_lock(report)),
                  (NATIVE_LOCK_JSON, "native-packages.lock.json", json.dumps({"native_packages": native_packages}, indent=2)))
    if update_locks and any(package["version"] is None for package in native_packages):
        raise ValueError("cannot update canonical locks with unavailable native packages")
    for canonical, filename, text in candidates:
        (out_dir / filename).write_text(text, encoding="utf-8")
        if update_locks:
            canonical.write_text(text, encoding="utf-8")
    (out_dir / "release_locks.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    (out_dir / "release_locks.md").write_text(render_markdown(result), encoding="utf-8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate locked dependency-version artifacts for CR01-SC tagged releases.")
    parser.add_argument("--out", type=Path, default=Path("reports") / "release_locks")
    parser.add_argument("--update-locks", action="store_true", help="Explicitly replace canonical version locks after reviewing candidates.")
    args = parser.parse_args()

    result = generate_release_locks(args.out, update_locks=args.update_locks)
    summary = result["summary"]
    print(
        "Release locks complete: "
        f"python_packages={summary['python_runtime_package_count']}; "
        f"native_packages={summary['native_package_count']}; "
        f"out={args.out}"
    )


if __name__ == "__main__":
    main()
